#!/bin/sh
# 3568 上的 SSH 中继：把本机 2222 端口转给 K1 的 22 端口。
#
# 为什么要在 3568 上绕一道：PC 不在 192.168.88.0/24，而 3568 两个网口
# 分别接 K1 与 PC。用 hdc 的 fport 把 PC 的 2222 送到 3568 的 2222，
# 再由这里的 nc 接到 K1:22，全程不需要 PC 改 IP、不需要管理员权限。
#
# 用 -lk 而不是 -l：ssh/scp 会开多条连接，-l 只服务一次就退出。
# -e 的实参必须放在最后，busybox nc 的解析规则如此。
exec busybox nc -lk -p 2222 -e "busybox nc 192.168.88.10 22"
